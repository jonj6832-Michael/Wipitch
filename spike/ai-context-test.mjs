import assert from 'node:assert/strict';
import { contextCorrectionNotes } from '../src/model/context-correction.ts';
import { applyCorrection } from '../src/model/auto-pitch.ts';
import { createAIRegions, regionCurves, reviewedAIRegions, syncAIRegion } from '../src/model/ai-regions.ts';
import { Curves, CURVE_HOP_SEC } from '../src/model/curves.ts';
import { History } from '../src/model/history.ts';
import { KEY_OPTIONS } from '../src/model/keys.ts';
const key=KEY_OPTIONS.find(k=>k.id==='major-0');
const base=new Curves(1000),midi=new Float32Array(1000).fill(60),voiced=new Uint8Array(1000).fill(1);
voiced.fill(0,0,100);
for(let i=100;i<140;i++)midi[i]=59.4+.6*(i-100)/40;
const onset=contextCorrectionNotes(base,midi,voiced,key,{start:.2,end:1.8});
assert.ok(onset.some(n=>n.kind==='onset'),'short voiced onset should use following stable target');
const notes=onset.filter(n=>n.kind==='onset');
const after=applyCorrection(base,notes,notes.map(n=>({id:n.id,targetMidi:n.defaultTarget})),key,10,voiced).curves;
const regions=createAIRegions(base,after,notes),r=regions[0];
const restored=regionCurves(after,r,false);
assert.deepEqual(restored.pitch,base.pitch);
assert.deepEqual(regionCurves(restored,r,true).pitch,after.pitch);
const manual=regionCurves(after,r,true,.3);
for(let i=0;i<base.length;i++)if(i<r.from||i>=r.to)assert.equal(manual.pitch[i],after.pitch[i]);
syncAIRegion(r,manual);assert.equal(r.edited,true);
r.feedbackType='adjusted';syncAIRegion(r,manual);assert.equal(r.feedbackType,'adjusted','explicit user feedback must survive curve resynchronization');
syncAIRegion(r,restored);assert.equal(r.enabled,false);assert.equal(r.edited,false);assert.equal(r.offset,0);
assert.deepEqual(regionCurves(restored,r,true).pitch,after.pitch);
r.feedbackType='rejected';syncAIRegion(r,after);assert.equal(r.enabled,true);assert.equal(r.edited,false);assert.equal(r.feedbackType,'rejected','overlapping curve state must not erase a rejected review action');
const inferred={...r,feedbackType:undefined,enabled:false,edited:true};
assert.deepEqual(reviewedAIRegions([inferred]),[],'curve state alone must not create AI feedback');
assert.deepEqual(reviewedAIRegions([{...inferred,feedbackType:'rejected'},{...inferred,feedbackType:'adjusted'}]).map(x=>x.feedbackType),['rejected','adjusted']);
const history=new History();history.reset(base);history.push(base);history.push(after);history.truncate(0);
assert.equal(history.depth,0);assert.equal(history.redoDepth,0);
// Local long-note drift, stable on each side.
midi.fill(60);voiced.fill(1);midi.fill(60.35,400,470);
const drift=contextCorrectionNotes(base,midi,voiced,key,{start:0,end:2});
assert.ok(drift.some(n=>n.kind==='drift'),'sustained local drift should use matching stable anchors');
// Silence and irregular broad glides must not become short-onset fixes without stable evidence.
voiced.fill(0);assert.equal(contextCorrectionNotes(base,midi,voiced,key,{start:0,end:2}).length,0);
voiced.fill(1);for(let i=0;i<1000;i++)midi[i]=60+.2*Math.sin(i*CURVE_HOP_SEC*2*Math.PI*5);
assert.equal(contextCorrectionNotes(base,midi,voiced,key,{start:0,end:2}).filter(n=>n.kind==='drift').length,0);
console.log('context: onset, sustained drift, vibrato exclusion, per-region restore/reapply/edit and containment passed');
